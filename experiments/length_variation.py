"""
Length Variation Style Experiment (BATCHED) + DATA CACHING

Applies LLM-based prompt length variation (expand/compress) and measures
the effect on model behaviour across multiple axes.

Styled prompts are generated by an external LLM (Gemini / OpenAI) and
cached in data/llm_style_cache/ so they are only generated once.

Run:
  python experiments/length_variation.py \
    --models L3.2-3B \
    --dataset truthful_qa --sample_size 128 \
    --experiments all \
    --multipliers 0.25 0.5 1.5 2.0 \
    --rewrite_provider gemini --rewrite_model gemini-2.0-flash-lite \
    --batch_size 16
"""


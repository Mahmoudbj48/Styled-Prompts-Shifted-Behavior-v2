def run_experiment(
        models: List[str],
        dataset_name: str,
        sample_size: Optional[int],
        experiments: Optional[List[str]],
        *,
        batch_size: int,
        max_new_tokens: Optional[int],
        show_row_pbar: bool,
        multipliers_explicit: Optional[List[float]],
        rewrite_provider: str,
        rewrite_model: str,
        rewrite_api_key_env: str,
        data_dir: str,
        overwrite_sample_cache: bool,
        overwrite_output_cache: bool,
        overwrite_style_cache: bool,
        places_override: Optional[List[str]] = None,
) -> str:
    config = load_config()
    experiments_set = _normalize_experiments(experiments)

    if dataset_name not in config["datasets"]:
        raise ValueError(f"Dataset '{dataset_name}' not found. Available: {list(config['datasets'].keys())}")
    dataset_config = config["datasets"][dataset_name]

    if sample_size is None:
        sample_size = int(dataset_config["sample_size"])

    multipliers = _select_multipliers(
        config_multipliers=config["style_levels"].get("length_variation", [0.25, 0.5, 1.0, 1.5, 2.0, 3.0]),
        explicit_multipliers=multipliers_explicit,
    )

    if max_new_tokens is None:
        max_new_tokens = int(config["defaults"].get("max_new_tokens", 256))

    # --- Places (default: global only, since length variation is a global rewrite) ---
    if places_override:
        places = [p for p in places_override if p in {"prefix", "suffix", "global"}]
    else:
        places = [p for p in config.get("style_positions", {}).get("length_variation", ["global"])]
        places = [p for p in places if p in {"prefix", "suffix", "global"}]
    if not places:
        places = ["global"]

    # --- Output directory ---
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    base_results_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), "results")
    style_dir = os.path.join(base_results_dir, STYLE_NAME)
    run_dir = os.path.join(style_dir, f"run_multi_{dataset_name}_{timestamp}")
    os.makedirs(run_dir, exist_ok=True)

    print(f"\n{'=' * 80}")
    print("LENGTH VARIATION EXPERIMENT (MULTI-MODEL, BATCHED) + DATA CACHING")
    print(f"{'=' * 80}")
    print(f"Models:            {models}")
    print(f"Dataset:           {dataset_name}")
    print(f"Experiments:       {sorted(experiments_set)}")
    print(f"Sample size:       {sample_size}")
    print(f"Multipliers:       {multipliers}")
    print(f"Places:            {places}")
    print(f"Rewrite LLM:       {rewrite_provider}/{rewrite_model}")
    print(f"Batch size:        {batch_size}")
    print(f"Max new tokens:    {max_new_tokens}")
    print(f"Data cache dir:    {data_dir}")
    print(f"Output dir:        {run_dir}")
    print(f"{'=' * 80}\n")

    # --- Load / cache dataset sample ---
    items = _load_or_create_sample(
        data_dir=data_dir,
        dataset=dataset_name,
        config_name=dataset_config.get("config_name"),
        split=dataset_config.get("split", "validation"),
        seed=int(config["defaults"]["random_seed"]),
        sample_size=int(sample_size),
        overwrite_sample_cache=bool(overwrite_sample_cache),
    )

    prompts = [_get_prompt_text(it) for it in items]

    # --- Pre-generate styled prompts for ALL multipliers ---
    styled_prompts_by_mult: Dict[float, List[str]] = {}
    for mult in multipliers:
        styled_prompts_by_mult[mult] = load_or_generate_styled_prompts(
            data_dir=data_dir,
            dataset=dataset_name,
            prompts=prompts,
            style_name="length_variation",
            param=mult,
            rewrite_provider=rewrite_provider,
            rewrite_model=rewrite_model,
            rewrite_api_key_env=rewrite_api_key_env,
            overwrite=overwrite_style_cache,
        )

    # --- Run per model ---
    all_dfs = []
    for model_name in models:
        model_path = config["models"][model_name]
        df_model = run_for_one_model(
            model_name=model_name,
            model_path=model_path,
            items=items,
            multipliers=multipliers,
            styled_prompts_by_mult=styled_prompts_by_mult,
            config=config,
            run_dir=run_dir,
            experiments=experiments_set,
            places=places,
            batch_size=batch_size,
            max_new_tokens=max_new_tokens,
            show_row_pbar=show_row_pbar,
            data_dir=data_dir,
            dataset_name=dataset_name,
            dataset_config_name=dataset_config.get("config_name"),
            dataset_split=dataset_config.get("split", "validation"),
            dataset_seed=int(config["defaults"]["random_seed"]),
            dataset_sample_size=int(sample_size),
            overwrite_output_cache=bool(overwrite_output_cache),
        )
        if df_model is not None and not df_model.empty:
            all_dfs.append(df_model)

    if not all_dfs:
        print("No outputs produced (check experiments selection).")
        return run_dir

    df_all = pd.concat(all_dfs, ignore_index=True)

    full_path = os.path.join(run_dir, "full_results_all_models.csv")
    df_all.to_csv(full_path, index=False)
    print(f"✓ Saved combined full results: {full_path}")

    # --- Generate plots ---
    try:
        from utils.surface_plots import make_all_plots_from_csvs

        plot_dir = os.path.join(run_dir, "plots_metrics")
        os.makedirs(plot_dir, exist_ok=True)

        # surface_plots expects integer strengths in its x-axis tick logic;
        # we pass None so it auto-detects from the CSV.
        make_all_plots_from_csvs(
            plot_inputs=[run_dir],
            out_dir=plot_dir,
            strengths=None,
            places_filter=places,
            models_filter=models,
            dataset_name=dataset_name,
            style_name=STYLE_NAME,
            save_pdf=False,
            include_title=False,
            legend_outside=True,
        )
        print(f"✓ Generated plots: {plot_dir}")
    except ImportError:
        print("⚠️ Plotting module not found — skipping plots")
    except Exception as e:
        print(f"⚠️ Plotting failed: {e}")

    # --- Structuredness-specific plots (length ratio boxplots) ---
    try:
        from utils.structuredness_plots import make_structuredness_plots

        struct_plot_dir = os.path.join(run_dir, "plots_structuredness")
        make_structuredness_plots(
            df_all, struct_plot_dir,
            dataset_name=dataset_name,
            models_filter=models,
            save_pdf=False,
        )
        print(f"✓ Generated structuredness plots: {struct_plot_dir}")
    except ImportError:
        print("⚠️ structuredness_plots not found — skipping")
    except Exception as e:
        print(f"⚠️ Structuredness plots failed: {e}")

    return run_dir



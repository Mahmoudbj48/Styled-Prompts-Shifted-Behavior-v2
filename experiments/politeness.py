    parser.add_argument("--batch_size", type=int, default=21)
    parser.add_argument("--max_new_tokens", type=int, default=None)
    parser.add_argument("--show_row_pbar", action="store_true")

    parser.add_argument("--places", nargs="+", default=None, help="Override places for run (e.g., --places prefix)")

    parser.add_argument("--strengths", nargs="+", type=int, default=None)
    parser.add_argument("--strength_range", nargs=2, type=int, default=None, metavar=("LO", "HI"))
    parser.add_argument("--strength_step", type=int, default=1)


def _safe_name(x: Optional[str]) -> str:
    """Sanitise a value for use in file or directory names."""
    if x is None:
        return "none"
    x = str(x)
    return "".join([c if c.isalnum() or c in ("-", "_", ".", "=") else "_" for c in x])


def _sample_cache_dir(
        *,
        data_dir: str,
        dataset: str,
        config_name: Optional[str],
        split: str,
        seed: int,
        sample_size: int,
) -> str:
    """Return the directory path for the cached dataset sample."""
    return os.path.join(
        data_dir,
        "samples",
        _safe_name(dataset),
        f"config_{_safe_name(config_name)}",
        f"split_{_safe_name(split)}",
        f"seed_{seed}",
        f"n_{sample_size}",
    )


def _sample_cache_path(sample_dir: str) -> str:
    """Return the path for the sample JSONL file within its cache directory."""
    return os.path.join(sample_dir, "sample.jsonl")


def _meta_path(sample_dir: str) -> str:
    """Return the path for the sample metadata YAML file within its cache directory."""
    return os.path.join(sample_dir, "meta.yaml")


def _write_jsonl(path: str, rows: List[dict]) -> None:
    """Write a list of dicts to a JSONL file, creating parent directories as needed."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


def _read_jsonl(path: str) -> List[dict]:
    """Read a JSONL file and return a list of dicts, skipping blank lines."""
    out = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            out.append(json.loads(line))
    return out


def _write_yaml(path: str, obj: dict) -> None:
    """Write a dict to a YAML file, creating parent directories as needed."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        yaml.safe_dump(obj, f, sort_keys=False)


def _load_or_create_sample(
        *,
        data_dir: str,
        dataset: str,
        config_name: Optional[str],
        split: str,
        seed: int,
        sample_size: int,
        overwrite_sample_cache: bool,
) -> List[dict]:
    sdir = _sample_cache_dir(
        data_dir=data_dir,
        dataset=dataset,
        config_name=config_name,
        split=split,
        seed=seed,
        sample_size=sample_size,
    )
    spath = _sample_cache_path(sdir)
    mpath = _meta_path(sdir)

    if os.path.exists(spath) and (not overwrite_sample_cache):
        items = _read_jsonl(spath)
        if len(items) == sample_size:
            return items

    items = load_dataset_by_name(
        dataset,
        sample_size=sample_size,
        seed=seed,
        config_name=config_name,
        split=split,
    )
    os.makedirs(sdir, exist_ok=True)
    _write_jsonl(spath, items)
    _write_yaml(mpath, {
        "dataset": dataset,
        "config_name": config_name,
        "split": split,
        "seed": seed,
        "sample_size": sample_size,
        "created_at": datetime.now().isoformat(timespec="seconds"),
    })
    return items



# experiments/politeness.py
"""
Politeness style experiment with batched generation, optional LLM-as-judge mirroring,
prompt/output caching, and plot generation from saved CSVs.

Applies politeness framing (positive and negative strengths, at prefix/suffix/global
positions) to prompts and measures model behavioural changes across multiple axes.

Inputs:
    - Dataset prompts (TruthfulQA or Natural Questions via utils.data.load_dataset_by_name)
    - config.yaml for model paths, default strengths, and style positions
    - Optional: OPENAI_API_KEY or GEMINI_API_KEY for LLM-as-judge mirroring evaluation

Outputs (saved to results/politeness/run_YYYYMMDD_HHMMSS/):
    - {model}_results.csv: per-example metrics for each model
    - full_results_all_models.csv: combined per-example metrics across all models
    - summary_all_models.csv: mean metrics per (model, place, strength)
    - Plots generated by reloading saved CSVs via utils.plots

Run:
  export OPENAI_API_KEY="..."
  python experiments/politeness.py \\
    --models L3-8B \\
    --dataset truthful_qa --sample_size 64 \\
    --experiments all \\
    --places prefix \\
    --strength_range -10 10 --strength_step 2 \\
    --judge_provider openai --judge_model gpt-4o-mini \\
    --batch_size 16

Important flags:
    --experiments   Axes to compute: prompt, response, activation, confidence, mirroring (or all)
    --places        Placement strategy: prefix, suffix, global
    --strengths     Explicit list of strength values
    --strength_range LO HI --strength_step K  Alternative to --strengths
    --judge_provider / --judge_model  LLM provider and model for mirroring evaluation
"""


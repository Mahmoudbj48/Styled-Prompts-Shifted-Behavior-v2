def _normalize_experiments(experiments: Optional[List[str]]) -> Set[str]:
    """Validate and expand experiment axis names; 'all' returns every valid experiment."""
    if experiments is None:
        return set(VALID_EXPERIMENTS)

    exp = [e.strip().lower() for e in experiments]
    if "all" in exp:
        return set(VALID_EXPERIMENTS)

    unknown = [e for e in exp if e not in VALID_EXPERIMENTS]
    if unknown:
        raise ValueError(f"Unknown experiments: {unknown}. Valid: {sorted(VALID_EXPERIMENTS)} or 'all'.")
    return set(exp)


def _normalize_models(models: List[str], config: dict) -> List[str]:
    """Validate model keys against config; 'all' returns every available model."""
    available = list(config.get("models", {}).keys())
    if not available:
        raise ValueError("No models found in config.yaml under 'models'.")

    # Model alias keys are case-sensitive (e.g. "L3-8B"); preserve original casing.
    m = [x.strip() for x in models]
    if len(m) == 1 and m[0].lower() == "all":
        return available

    unknown = [x for x in m if x not in available]
    if unknown:
        raise ValueError(f"Unknown models: {unknown}. Available: {available} or 'all'.")
    return m


def _get_places(config: dict) -> List[str]:
    """Read politeness style positions from config, excluding 'middle'."""
    places = [p for p in config.get("style_positions", {}).get("politeness", []) if p != "middle"]
    if not places:
        places = ["prefix", "suffix", "global"]
    places = [p for p in places if p in {"prefix", "suffix", "global"}]
    if not places:
        raise ValueError("No valid politeness positions after excluding 'middle'. Use prefix/suffix/global.")
    return places


def _num_batches(n: int, bs: int) -> int:
    """Return the number of batches needed to cover n items with batch size bs."""
    return (n + bs - 1) // bs


def _select_strengths(
        *,
        config_strengths: List[int],
        explicit_strengths: Optional[List[int]],
        strength_range: Optional[Tuple[int, int]],
        strength_step: int,
) -> List[int]:
    """
    Priority:
      1) explicit_strengths
      2) strength_range (grid)
      3) config_strengths
    """
    if explicit_strengths:
        out, seen = [], set()
        for s in explicit_strengths:
            s = int(s)
            if s not in seen:
                out.append(s)
                seen.add(s)
        return out

    if strength_range is not None:
        lo, hi = strength_range
        if strength_step <= 0:
            raise ValueError("--strength_step must be >= 1")
        if lo > hi:
            lo, hi = hi, lo
        return list(range(int(lo), int(hi) + 1, int(strength_step)))

    return [int(x) for x in config_strengths]


def _get_prompt_text(item: dict) -> str:
    """Extract the prompt string from a dataset item dict, trying 'question' then 'prompt'."""
    if "question" in item and item["question"]:
        return str(item["question"])
    if "prompt" in item and item["prompt"]:
        return str(item["prompt"])
    return str(item)



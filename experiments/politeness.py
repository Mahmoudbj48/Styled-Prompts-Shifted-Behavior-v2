def run_for_one_model(
        model_name: str,
        model_path: str,
        items: List[dict],
        strength_levels: List[int],
        places: List[str],
        config: dict,
        run_dir: str,
        experiments: Set[str],
        *,
        batch_size: int,
        max_new_tokens: int,
        show_row_pbar: bool = False,
        # mirroring judge params
        judge_provider: str = "openai",
        judge_model: str = "gpt-4o-mini",
        openai_key_env: str = "OPENAI_API_KEY",
        gemini_key_env: str = "GEMINI_API_KEY",
        judge_max_output_tokens: int = 16,
        max_mirroring_judge_calls: int = 999999999,
        # data cache params
        data_dir: str,
        dataset_name: str,
        dataset_config_name: Optional[str],
        dataset_split: str,
        dataset_seed: int,
        dataset_sample_size: int,
        style_name: str,
        overwrite_output_cache: bool,
) -> pd.DataFrame:

    llm_experiments = {"response", "activation", "confidence", "mirroring"}
    run_llm_phase = len(experiments.intersection(llm_experiments)) > 0

    model = None
    tokenizer = None
    if run_llm_phase:
        model, tokenizer = load_model(
            model_path,
            device_map=config["defaults"].get("device_map", "auto"),
            dtype=config["defaults"].get("dtype", "float32"),
        )

    seed = int(config["defaults"].get("random_seed", 42))

    activations_cache = {(place, s): [] for place in places for s in strength_levels} if "activation" in experiments else None
    rows: List[dict] = []

    prompts_text = [_get_prompt_text(it) for it in items]
    categories = [it.get("category", "Unknown") for it in items]

    n = len(prompts_text)
    n_batches = _num_batches(n, batch_size)

    total_groups = n_batches * len(places) * len(strength_levels)
    batch_pbar = tqdm(total=total_groups, desc=f"[{model_name}] batch-groups", unit="group")

    row_pbar = None
    if show_row_pbar:
        total_rows = n * len(places) * len(strength_levels)
        row_pbar = tqdm(total=total_rows, desc=f"[{model_name}] rows", unit="row", leave=False)

    mirroring_calls_used = 0

    for b in range(n_batches):
        start = b * batch_size
        end = min(start + batch_size, n)

        batch_ids = list(range(start, end))
        batch_orig_prompts = prompts_text[start:end]
        batch_categories = categories[start:end]

        # Baseline activations for this batch
        batch_act_orig = None
        if run_llm_phase and ("activation" in experiments):
            batch_act_orig = get_layer_activations_batch(
                model, tokenizer,
                prompts=batch_orig_prompts,
                layer_idx=-1,
            )
            if batch_act_orig.shape[0] != len(batch_orig_prompts):
                raise RuntimeError("get_layer_activations_batch returned wrong batch size.")

        for place in places:
            for strength in strength_levels:
                batch_pert_prompts = [apply_politeness(p, strength, place=place) for p in batch_orig_prompts]

                # Prompt BERTScore (BATCHED)
                batch_prompt_bs = None
                if "prompt" in experiments:
                    batch_prompt_bs = compute_bertscore_batch(
                        references=batch_orig_prompts,
                        candidates=batch_pert_prompts,
                        device="cpu",
                        model_type="roberta-large",
                        batch_size=min(32, max(1, len(batch_orig_prompts))),
                    )

                # Responses (baseline + styled) with caching
                batch_response_orig = None
                batch_response_pert = None
                batch_response_orig_clean = None
                batch_response_pert_clean = None

                if run_llm_phase and ("response" in experiments or "confidence" in experiments or "mirroring" in experiments):
                    cache_path = _outputs_cache_path(
                        data_dir=data_dir,
                        dataset=dataset_name,
                        config_name=dataset_config_name,
                        split=dataset_split,
                        seed=dataset_seed,
                        sample_size=dataset_sample_size,
                        model_name=model_name,
                        style=style_name,
                        place=place,
                        strength=int(strength),
                    )
                    out = _load_or_generate_outputs_for_bucket(
                        cache_path=cache_path,
                        overwrite_output_cache=overwrite_output_cache,
                        model=model,
                        tokenizer=tokenizer,
                        prompt_orig_list=batch_orig_prompts,
                        prompt_styled_list=batch_pert_prompts,
                        max_new_tokens=max_new_tokens,
                        batch_size=batch_size,
                    )
                    batch_response_orig = out["output_orig_raw"]
                    batch_response_pert = out["output_styled_raw"]
                    batch_response_orig_clean = out["output_orig_clean"]
                    batch_response_pert_clean = out["output_styled_clean"]

                # Response BERTScore (BATCHED)
                batch_response_bs = None
                if run_llm_phase and ("response" in experiments):
                    # Use CPU to avoid fighting GPU memory with the main LLM.
                    batch_response_bs = compute_bertscore_batch(
                        references=batch_response_orig,
                        candidates=batch_response_pert,
                        device="cpu",
                        model_type="roberta-large",
                        batch_size=min(16, max(1, len(batch_response_orig))),
                    )

                # Styled activations
                batch_act_pert = None
                if run_llm_phase and ("activation" in experiments):
                    batch_act_pert = get_layer_activations_batch(
                        model, tokenizer,
                        prompts=batch_pert_prompts,
                        layer_idx=-1,
                    )
                    if batch_act_pert.shape[0] != len(batch_pert_prompts):
                        raise RuntimeError("get_layer_activations_batch returned wrong batch size (styled).")

                # Mirroring
                mir_yes = 0
                mir_total = 0
                mir_rate = np.nan
                mirroring_verdicts: List[Optional[bool]] = [None] * len(batch_orig_prompts)
                mirroring_raws: List[str] = [""] * len(batch_orig_prompts)

                if "mirroring" in experiments:
                    for j in range(len(batch_orig_prompts)):
                        if mirroring_calls_used >= max_mirroring_judge_calls:
                            break
                        verdict, judge_raw, _ = judge_with_retries(
                            judge_provider=judge_provider,
                            original_prompt=batch_orig_prompts[j],
                            original_output=batch_response_orig_clean[j],
                            styled_prompt=batch_pert_prompts[j],
                            styled_output=batch_response_pert_clean[j],
                            style_name="politeness",
                            strength=int(strength),
                            place=place,
                            judge_model=judge_model,
                            openai_key_env=openai_key_env,
                            gemini_key_env=gemini_key_env,
                            max_output_tokens=judge_max_output_tokens,
                            use_false_positive_guard=True,
                        )
                        mirroring_calls_used += 1
                        mirroring_verdicts[j] = verdict
                        mirroring_raws[j] = judge_raw or ""

                        if verdict is not None:
                            mir_total += 1
                            if verdict:
                                mir_yes += 1

                    if mir_total > 0:
                        mir_rate = mir_yes / mir_total

                # Per-example rows (include everything needed for plotting)
                for j in range(len(batch_orig_prompts)):
                    i = batch_ids[j]
                    orig = batch_orig_prompts[j]
                    pert = batch_pert_prompts[j]
                    cat = batch_categories[j]

                    row = {
                        "model": model_name,
                        "prompt_id": i,
                        "place": place,
                        "strength": int(strength),
                        "category": cat,
                        "prompt_orig": orig,
                        "prompt_pert": pert,
                    }

                    if "prompt" in experiments:
                        row["bertscore_prompt"] = float(batch_prompt_bs[j])

                    if run_llm_phase and ("response" in experiments or "confidence" in experiments or "mirroring" in experiments):
                        row["response_orig"] = batch_response_orig[j]
                        row["response_pert"] = batch_response_pert[j]

                    if run_llm_phase and ("response" in experiments):
                        ro = batch_response_orig[j]
                        rp = batch_response_pert[j]
                        row["bleu"] = float(compute_bleu(ro, rp))
                        row["bertscore_response"] = float(batch_response_bs[j])

                    if run_llm_phase and ("activation" in experiments):
                        a0 = batch_act_orig[j]
                        a1 = batch_act_pert[j]
                        row["activation_similarity"] = float(F.cosine_similarity(a0.unsqueeze(0), a1.unsqueeze(0)).item())
                        activations_cache[(place, strength)].append(a1.detach())

                    if run_llm_phase and ("confidence" in experiments):
                        conf = compute_confidence(model, tokenizer, orig, pert, batch_response_orig[j])
                        row.update(conf)

                    if "mirroring" in experiments:
                        row["mirroring_verdict"] = (
                            "YES" if mirroring_verdicts[j] is True else
                            "NO" if mirroring_verdicts[j] is False else
                            ""
                        )
                        row["mirroring_judge_raw"] = mirroring_raws[j]
                        row["mirroring_rate_batch"] = float(mir_rate) if np.isfinite(mir_rate) else np.nan

                    rows.append(row)
                    if row_pbar is not None:
                        row_pbar.update(1)

                batch_pbar.update(1)

    batch_pbar.close()
    if row_pbar is not None:
        row_pbar.close()

    df = pd.DataFrame(rows)
    df = add_delta_columns(df, style="politeness")

    out_csv = os.path.join(run_dir, f"{model_name}_results.csv")
    df.to_csv(out_csv, index=False)
    print(f"✓ Saved per-example results: {out_csv}")

    # t-SNE plots (kept)
    if "activation" in experiments and activations_cache is not None:

        plot_dir = os.path.join(run_dir, "plots_tsne", model_name)
        os.makedirs(plot_dir, exist_ok=True)
        viz_sample_size = min(50, len(items))

        # ---- Ordinal color setup ----
        strength_sorted = sorted(strength_levels)
        norm = mpl.colors.Normalize(
            vmin=min(strength_sorted),
            vmax=max(strength_sorted)
        )
        cmap = mpl.cm.viridis  # perceptually uniform (good for ordinal data)

        for place in places:
            fig, ax = plt.subplots(figsize=(10, 7))

            for strength in strength_sorted:
                acts = activations_cache[(place, strength)][:viz_sample_size]
                if len(acts) < 2:
                    continue

                coords = reduce_activations_2d(acts, method="tsne", seed=seed)

                ax.scatter(
                    coords[:, 0],
                    coords[:, 1],
                    alpha=0.75,
                    s=40,
                    color=cmap(norm(strength))
                )

            # Title
            ax.set_title(f"t-SNE Activations (last layer) - {model_name} - {place}")

            # Remove axes
            ax.set_axis_off()

            # Add black rectangle border
            rect = Rectangle(
                (0, 0), 1, 1,
                transform=ax.transAxes,
                fill=False,
                edgecolor="black",
                linewidth=2,
                clip_on=False
            )
            ax.add_patch(rect)

            # Add colorbar (important for ordinal meaning)
            sm = mpl.cm.ScalarMappable(norm=norm, cmap=cmap)
            sm.set_array([])
            cbar = fig.colorbar(sm, ax=ax, fraction=0.046, pad=0.04)
            cbar.set_label("Strength (ordinal)")

            plt.tight_layout()
            plt.savefig(
                os.path.join(plot_dir, f"tsne_{place}.png"),
                dpi=250,
                bbox_inches="tight",
                pad_inches=0.1
            )
            plt.close(fig)

    return df



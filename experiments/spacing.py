# Global runner (multi-model)
# --------------------------
def run_experiment(
        models: List[str],
        dataset_name: str,
        sample_size: Optional[int],
        experiments: Optional[List[str]],
        *,
        batch_size: int,
        max_new_tokens: Optional[int],
        show_row_pbar: bool,
        strengths_explicit: Optional[List[int]],
        strength_range: Optional[Tuple[int, int]],
        strength_step: int,
        judge_provider: str,
        judge_model: str,
        openai_key_env: str,
        gemini_key_env: str,
        judge_max_output_tokens: int,
        max_mirroring_judge_calls: int,
        data_dir: str,
        overwrite_sample_cache: bool,
        overwrite_output_cache: bool,
        places_override: Optional[List[str]],
) -> str:
    config = load_config()
    experiments_set = _normalize_experiments(experiments)

    if dataset_name not in config["datasets"]:
        raise ValueError(f"Dataset '{dataset_name}' not found. Available: {list(config['datasets'].keys())}")
    dataset_config = config["datasets"][dataset_name]

    if sample_size is None:
        sample_size = int(dataset_config["sample_size"])

    places = places_override if (places_override and len(places_override) > 0) else _get_places(config)

    strength_levels = _select_strengths(
        config_strengths=config["style_levels"]["spacing"],
        explicit_strengths=strengths_explicit,
        strength_range=strength_range,
        strength_step=strength_step,
    )

    if max_new_tokens is None:
        max_new_tokens = int(config["defaults"].get("max_new_tokens", 256))

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    base_results_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), "results")
    style_dir = os.path.join(base_results_dir, "spacing")
    run_dir = os.path.join(style_dir, f"run_multi_{dataset_name}_{timestamp}")
    os.makedirs(run_dir, exist_ok=True)

    print(f"\n{'='*80}")
    print("SPACING EXPERIMENT (MULTI-MODEL, BATCHED) + DATA CACHING")
    print(f"{'='*80}")
    print(f"Models: {models}")
    print(f"Dataset: {dataset_name}")
    print(f"Experiments: {sorted(experiments_set)}")
    print(f"Sample size: {sample_size}")
    print(f"Strengths: {strength_levels}")
    print(f"Places: {places}")
    print(f"Batch size: {batch_size}")
    print(f"Max new tokens: {max_new_tokens}")
    print(f"Data cache dir: {data_dir}")
    print(f"Overwrite sample cache: {overwrite_sample_cache}")
    print(f"Overwrite output cache: {overwrite_output_cache}")
    if "mirroring" in experiments_set:
        print(f"Mirroring judge: {judge_provider}/{judge_model}  max_calls={max_mirroring_judge_calls}")
    print(f"Output dir (results): {run_dir}")
    print(f"{'='*80}\n")

    items = _load_or_create_sample(
        data_dir=data_dir,
        dataset=dataset_name,
        config_name=dataset_config.get("config_name"),
        split=dataset_config.get("split", "validation"),
        seed=int(config["defaults"]["random_seed"]),
        sample_size=int(sample_size),
        overwrite_sample_cache=bool(overwrite_sample_cache),
    )

    all_rows = []
    for model_name in models:
        model_path = config["models"][model_name]
        df_model = run_for_one_model(
            model_name=model_name,
            model_path=model_path,
            items=items,
            strength_levels=strength_levels,
            places=places,
            config=config,
            run_dir=run_dir,
            experiments=experiments_set,
            batch_size=batch_size,
            max_new_tokens=max_new_tokens,
            show_row_pbar=show_row_pbar,
            judge_provider=judge_provider,
            judge_model=judge_model,
            openai_key_env=openai_key_env,
            gemini_key_env=gemini_key_env,
            judge_max_output_tokens=judge_max_output_tokens,
            max_mirroring_judge_calls=max_mirroring_judge_calls,
            data_dir=data_dir,
            dataset_name=dataset_name,
            dataset_config_name=dataset_config.get("config_name"),
            dataset_split=dataset_config.get("split", "validation"),
            dataset_seed=int(config["defaults"]["random_seed"]),
            dataset_sample_size=int(sample_size),
            style_name="spacing",
            overwrite_output_cache=bool(overwrite_output_cache),
        )
        if df_model is not None and not df_model.empty:
            all_rows.append(df_model)

    if not all_rows:
        print("No outputs produced (check experiments selection).")
        return run_dir

    df_all = pd.concat(all_rows, ignore_index=True)

    full_path = os.path.join(run_dir, "full_results_all_models.csv")
    df_all.to_csv(full_path, index=False)
    print(f"✓ Saved combined full results: {full_path}")

    return run_dir


def main():
    parser = argparse.ArgumentParser(description="Run spacing style experiment (multi-model, batched)")
    parser.add_argument("--models", nargs="+", default=["L3.2-1B"], help="Model keys from config or 'all'")
    parser.add_argument("--dataset", type=str, default="truthful_qa")
    parser.add_argument("--sample_size", type=int, default=None)
    parser.add_argument("--experiments", nargs="+", default=["all"],
                        help="all OR subset of: prompt response activation confidence mirroring")

    parser.add_argument("--batch_size", type=int, default=21)
    parser.add_argument("--max_new_tokens", type=int, default=None)
    parser.add_argument("--show_row_pbar", action="store_true")

    parser.add_argument("--places", nargs="+", default=None, help="Override places for run (e.g., --places prefix)")

    parser.add_argument("--strengths", nargs="+", type=int, default=None)
    parser.add_argument("--strength_range", nargs=2, type=int, default=None, metavar=("LO", "HI"))
    parser.add_argument("--strength_step", type=int, default=1)

    parser.add_argument("--judge_provider", type=str, default="openai", choices=["openai", "gemini"])
    parser.add_argument("--judge_model", type=str, default="gpt-4o-mini")
